#!/usr/bin/env python3
"""Compile src/cuda/kernels.cu to PTX with NVRTC.

kLLM ships the generated PTX (src/cuda/kernels.ptx) so that building and
running it never needs a CUDA toolkit: at run time the NVIDIA driver JIT-
compiles the PTX for the installed GPU. Only maintainers who edit the .cu
file need NVRTC, e.g. from NVIDIA's wheel:

    python3 -m venv /tmp/nvrtc && /tmp/nvrtc/bin/pip install "nvidia-cuda-nvrtc-cu12==12.8.*"
    /tmp/nvrtc/bin/python scripts/build_ptx.py

The target is compute_50 (Maxwell), the oldest architecture kLLM supports;
the driver up-compiles it for newer GPUs.
"""
import ctypes, glob, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_path = os.path.join(root, "src", "cuda", "kernels.cu")
out_path = os.path.join(root, "src", "cuda", "kernels.ptx")

def find_nvrtc():
    if os.environ.get("NVRTC"):
        return os.environ["NVRTC"]
    for base in sys.path:
        hits = glob.glob(os.path.join(base, "nvidia", "cuda_nvrtc", "lib", "libnvrtc.so.*"))
        hits = [h for h in hits if ".alt." not in h]
        if hits:
            return hits[0]
    return "libnvrtc.so"

lib = ctypes.CDLL(find_nvrtc())
def check(code, what):
    if code != 0:
        lib.nvrtcGetErrorString.restype = ctypes.c_char_p
        raise SystemExit(f"{what}: {lib.nvrtcGetErrorString(code).decode()}")

source = open(src_path, "rb").read()
prog = ctypes.c_void_p()
check(lib.nvrtcCreateProgram(ctypes.byref(prog), source, b"kernels.cu", 0, None, None), "create")
options = [b"--gpu-architecture=compute_50", b"-std=c++17", b"--fmad=true", b"-default-device"]
arr = (ctypes.c_char_p * len(options))(*options)
code = lib.nvrtcCompileProgram(prog, len(options), arr)
size = ctypes.c_size_t()
lib.nvrtcGetProgramLogSize(prog, ctypes.byref(size))
log = ctypes.create_string_buffer(size.value)
lib.nvrtcGetProgramLog(prog, log)
if log.value.strip():
    print(log.value.decode(), file=sys.stderr)
check(code, "compile")
lib.nvrtcGetPTXSize(prog, ctypes.byref(size))
ptx = ctypes.create_string_buffer(size.value)
lib.nvrtcGetPTX(prog, ptx)
version = (ctypes.c_int(), ctypes.c_int())
lib.nvrtcVersion(ctypes.byref(version[0]), ctypes.byref(version[1]))
header = f"// Generated by scripts/build_ptx.py from kernels.cu with NVRTC {version[0].value}.{version[1].value}. Do not edit.\n"
open(out_path, "w").write(header + ptx.value.decode())
print(f"wrote {out_path} ({len(ptx.value)} bytes)")
